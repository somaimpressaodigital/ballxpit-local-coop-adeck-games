 static string LastLanguage;
 public static bool Portuguese {get{try{return CoopLocaleRules.UsesPortuguese(I2.Loc.LocalizationManager.CurrentLanguageCode,I2.Loc.LocalizationManager.CurrentLanguage);}catch{return false;}}}
 public static string LanguageKey {get{try{return Portuguese?I2.Loc.LocalizationManager.CurrentLanguage:"English";}catch{return "English";}}}
 public static string Text(string portuguese){return ForLanguage(portuguese,Portuguese);}
 public static string ForLanguage(string portuguese,bool usePortuguese){string translated;return usePortuguese||!English.TryGetValue(portuguese,out translated)?portuguese:translated;}
 public static string Relocalize(string stored){foreach(var pair in English)if(pair.Key==stored||pair.Value==stored)return Portuguese?pair.Key:pair.Value;return stored;}
 public static string Translate(string term){return I2.Loc.LocalizationManager.GetTranslation(term,overrideLanguage:Portuguese?null:"English");}
 public static string StageName(LevelInfo info){var text=Translate(info.GetNameSlug());return string.IsNullOrEmpty(text)||text.Contains("Missing Translation")?info.Type.ToString():text;}
 public static void Tick(){string language=LanguageKey;if(language==LastLanguage)return;LastLanguage=language;CoopCharacters.RefreshLocale();NativeChoiceOverlay.RefreshLocale();CoopVisuals.RefreshLocale();CoopCredits.RefreshLocale();}
